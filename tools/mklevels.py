#!/usr/bin/env python3
"""Build levels/oldrunner.lvl from the level designs below.

Each level is drawn with a few strokes on a 26x16 grid:
  F floor (#, or X for cement), L ladder, R rope, E escape ladder,
  G gold, B foe (bad guy), P player.
A floor at row r is walked on from row r-1; a ladder L(x, top, bottom) has
its top in the floor row it climbs to."""
import sys

W, H = 26, 16
AUTHOR = "Asciiverse"

class Lvl:
    def __init__(self, name):
        self.name = name
        self.g = [[' '] * W for _ in range(H)]
        self.F(15, 0, W - 1)
    def put(self, y, x, c):
        assert 0 <= y < H and 0 <= x < W, (self.name, y, x)
        self.g[y][x] = c
        return self
    def F(self, y, x0, x1, c='#'):
        for x in range(x0, x1 + 1): self.put(y, x, c)
        return self
    def V(self, x, y0, y1, c='#'):
        for y in range(y0, y1 + 1): self.put(y, x, c)
        return self
    def L(self, x, y0, y1): return self.V(x, y0, y1, 'H')
    def E(self, x, y0, y1): return self.V(x, y0, y1, '|')
    def R(self, y, x0, x1): return self.F(y, x0, x1, '-')
    def O(self, y, x0, x1): return self.F(y, x0, x1, ' ')
    def G(self, *ps):
        for y, x in ps: self.put(y, x, '$')
        return self
    def B(self, *ps):
        for y, x in ps: self.put(y, x, '&')
        return self
    def P(self, y, x): return self.put(y, x, '@')
    def text(self):
        out = ['#' + '-' * 77, f'level\t"{self.name}"', f'author\t"{AUTHOR}"', f'size\t{W}x{H}']
        out += ['[' + ''.join(r) + ']' for r in self.g]
        return '\n'.join(out) + '\n'

